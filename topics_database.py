def get_topics_for_genre(genre_name: str, lang: str = "uz") -> List[str]:
    """
    Tanlangan janr va tilga qarab toza va 100+ ta saralangan mavzular ro'yxatini qaytaradi.
    Ikkala janr (hikoyalar va faktlar) bir-biri bilan mutlaqo aralashmaydi.
    """
    genre_clean = (genre_name or "").lower()
    is_uz = lang.lower().startswith("uz")

    if "2d" in genre_clean or "hikoya" in genre_clean or "story" in genre_clean or "animat" in genre_clean:
        return STORY_ANIMATION_TOPICS_UZ if is_uz else STORY_ANIMATION_TOPICS_EN

    elif "fakt" in genre_clean or "kosmik" in genre_clean or "facts" in genre_clean or "space" in genre_clean or "hujjatli" in genre_clean:
        return COSMIC_FACTS_TOPICS_UZ if is_uz else COSMIC_FACTS_TOPICS_EN

    elif "shorts" in genre_clean or "vertikal" in genre_clean or "reels" in genre_clean:
        return SHORTS_VIRAL_TOPICS_UZ if is_uz else SHORTS_VIRAL_TOPICS_EN

    elif "motivatsiya" in genre_clean or "falsafa" in genre_clean or "stoic" in genre_clean:
        return MOTIVATION_STOIC_TOPICS_UZ if is_uz else MOTIVATION_STOIC_TOPICS_EN

    # Standart holatda faktlar
    return COSMIC_FACTS_TOPICS_UZ if is_uz else COSMIC_FACTS_TOPICS_EN
